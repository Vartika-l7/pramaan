"""Draft Certificate under Section 63 of the Bharatiya Sakshya Adhiniyam, 2023 (BSA).

Generates Part A (person in charge of device/system) and Part B (expert) drafts
with cryptographic hash values filled in and blank signature fields.
"""

from __future__ import annotations

from typing import Dict, List, Any


def generate_section_63_bsa_certificate_text(
    case_id: str,
    exhibits: List[Dict[str, Any]],
    merkle_root: str,
) -> str:
    """Generate plain text / markdown draft of Section 63 BSA certificate."""
    exhibit_rows = []
    for ex in exhibits:
        exhibit_rows.append(
            f"  - Exhibit {ex.get('exhibit_id')}: {ex.get('filename')} (SHA-256: {ex.get('sha256')})"
        )
    exhibit_listing = "\n".join(exhibit_rows)

    return f"""
================================================================================
DRAFT CERTIFICATE UNDER SECTION 63 OF THE BHARATIYA SAKSHYA ADHINIYAM, 2023
================================================================================
[Form for the Admission of Electronic Records in Court Proceedings]

NOTICE: Draft generated by software. Wording must be checked against the
Schedule to the Bharatiya Sakshya Adhiniyam, 2023 and signed by the responsible persons.

Case Reference: {case_id}
Consolidated Evidence Merkle Root: {merkle_root}

--------------------------------------------------------------------------------
PART A: CERTIFICATE BY THE PERSON IN CHARGE OF COMPUTER / DEVICE / SYSTEM
--------------------------------------------------------------------------------
I, [Name of System Administrator / Device Custodian], residing / working at
[Official Address / Police Station / Laboratory], do hereby solemnly affirm
and certify as follows:

1. That I am the person in lawful charge / custody / management of the computer
   system / server / mobile device described herein.
2. That during the period of operation, the computer / device was operating properly,
   and if at any time it was not operating properly, the same did not affect the
   electronic record or the accuracy of its contents.
3. That the electronic records produced and submitted in this case, listed below:
{exhibit_listing}
   were produced from the said computer / storage media during the ordinary course
   of regular digital forensics activities.
4. That the SHA-256 cryptographic hashes specified above were computed at the time
   of ingestion and verified against the tamper-evident hash chain.

Date: _______________                   Signature: _____________________________
Place: ______________                   Name: __________________________________
                                        Designation: ___________________________

--------------------------------------------------------------------------------
PART B: CERTIFICATE BY THE FORENSIC EXPERT
--------------------------------------------------------------------------------
I, [Name of Examiner / Forensics Expert], qualified Digital Forensics Examiner,
certify as follows:

1. That I have examined the electronic records listed in Part A above.
2. That I employed standardized, non-destructive forensic acquisition procedures
   using read-only storage and cryptographic hashing (SHA-256).
3. That the integrity of the evidence files has remained intact as verified by the
   cryptographic Merkle root {merkle_root}.
4. That the printout / output contains a true and accurate representation of the
   data stored in the electronic records examined.

Date: _______________                   Signature: _____________________________
Place: ______________                   Name: __________________________________
                                        Laboratory / Unit: _____________________
================================================================================
"""

